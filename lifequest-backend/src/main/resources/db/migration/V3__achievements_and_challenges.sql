CREATE TABLE IF NOT EXISTS user_achievements (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id BIGINT NOT NULL REFERENCES users(id),
 achievement_code VARCHAR(40) NOT NULL,unlocked_at TIMESTAMP WITH TIME ZONE NOT NULL,
 CONSTRAINT uq_user_achievement UNIQUE(user_id,achievement_code));
CREATE TABLE IF NOT EXISTS friend_challenges (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,creator_id BIGINT NOT NULL REFERENCES users(id),
 invitee_id BIGINT NOT NULL REFERENCES users(id),title VARCHAR(120) NOT NULL,target_xp INTEGER NOT NULL CHECK(target_xp BETWEEN 1 AND 100000),
 starts_at TIMESTAMP WITH TIME ZONE NOT NULL,ends_at TIMESTAMP WITH TIME ZONE NOT NULL,status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),CHECK(ends_at>starts_at));
CREATE TABLE IF NOT EXISTS team_challenges (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,creator_id BIGINT NOT NULL REFERENCES users(id),
 title VARCHAR(120) NOT NULL,target_xp INTEGER NOT NULL CHECK(target_xp BETWEEN 1 AND 100000),
 week_start DATE NOT NULL,created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS team_challenge_members (
 team_challenge_id BIGINT NOT NULL REFERENCES team_challenges(id) ON DELETE CASCADE,
 user_id BIGINT NOT NULL REFERENCES users(id),joined_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
 PRIMARY KEY(team_challenge_id,user_id));
CREATE INDEX IF NOT EXISTS idx_team_member_user ON team_challenge_members(user_id);
